-- Ejecutar conectado a db_parking como parking_migrator.
GRANT CONNECT ON DATABASE db_parking TO parking_app;
GRANT USAGE ON SCHEMA public TO parking_app;
GRANT SELECT, INSERT, UPDATE ON ALL TABLES IN SCHEMA public TO parking_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO parking_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT, INSERT, UPDATE ON TABLES TO parking_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO parking_app;
REVOKE DELETE ON ALL TABLES IN SCHEMA public FROM parking_app;
